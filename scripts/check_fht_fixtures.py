# ------------------------------------------------ independent R1-R5 reader --
# Written from the FORMAT.md rule text (and the round6 reference), separately
# from the generator's helpers.

def split_lines(data):
    """R1: return [(content, terminator)]; a line ends at LF, CRLF or lone CR."""
    lines, i, n = [], 0, len(data)
    while i < n:
        j = i
        while j < n and data[j] not in (0x0A, 0x0D):
            j += 1
        if j >= n:
            lines.append((data[i:j], b""))
            break
        elif data[j] == 0x0A:
            lines.append((data[i:j], b"\n"))
            i = j + 1
        elif j + 1 < n and data[j + 1] == 0x0A:
            lines.append((data[i:j], b"\r\n"))
            i = j + 2
        else:
            lines.append((data[i:j], b"\r"))
            i = j + 1
    return lines


def decompress(data):
    out = b""
    while data:
        engine = zlib.decompressobj(31)
        out += engine.decompress(data) + engine.flush()
        data = engine.unused_data
    return out


def header_lines(data):
    """R10: prefix lines of the leading block; raise if one follows a record."""
    block, in_records = [], False
    for content, _ in split_lines(data):
        if content.startswith(PREFIX):
            if in_records:
                raise ValueError("R10: a ';~' line appears after the first record")
            block.append(content[len(PREFIX):])
        elif content.startswith(b">"):
            in_records = True
    if not block:
        raise ValueError("R10: no header block")
    return block


B64 = rb"[A-Za-z0-9+/]{42}[AEIMQUYcgkosw048]="
VALUE_RE = re.compile(rb"^ +(?:(" + B64 + rb")|'(" + B64 + rb")'|\"(" + B64
                      + rb")\") *$")
KEY_RE = re.compile(rb"^([ \t]*)checksum( *):(.*)$", re.S)


def locate_checksum(data):
    """R2/R5: the single root-level checksum line; returns (stated, position,
    length). Raises ValueError when the shape is invalid."""
    lines = split_lines(data)
    blocks = header_lines(data)
    indents = [len(t) - len(t.lstrip(b" \t")) for t in blocks
               if t.strip() and not t.lstrip().startswith(b"#")]
    root_indent = min(indents)
    root = []
    for index, (content, term) in enumerate(lines):
        if not content.startswith(PREFIX):
            continue
        found = KEY_RE.match(content[len(PREFIX):])
        if found and len(found.group(1)) == root_indent:
            root.append((index, content + term, found))
    if len(root) != 1:
        raise ValueError(f"R2: {len(root)} root-level checksum lines (need 1)")
    _, whole, found = root[0]
    grammar = VALUE_RE.fullmatch(found.group(3))
    if not grammar:
        raise ValueError("R5: the checksum line holds more than the checksum value")
    stated = (grammar.group(1) or grammar.group(2) or grammar.group(3)).decode()
    position = data.find(whole)
    if position < 0 or data.count(whole) != 1:
        raise ValueError("R2: the checksum line is not uniquely locatable")
    return stated, position, len(whole)


def recomputed(data):
    """R3/R4: SHA-512/256 over every byte except the root checksum line."""
    _, position, length = locate_checksum(data)
    digest = hashlib.new("sha512_256", data[:position] + data[position + length:])
    return base64.b64encode(digest.digest()).decode("ascii")


def verify_stated(data):
    """Raise ValueError unless the stated root checksum equals the bytes."""
    stated, _, _ = locate_checksum(data)
    computed = recomputed(data)
    if stated != computed:
        raise ValueError("R3: stated checksum does not match the bytes")
    return stated


# ----------------------------------------------------- strict YAML rules ---
class StrictError(ValueError):
    pass


class StrictLoader(yaml.SafeLoader):
    """SafeLoader plus R8: duplicate keys, anchors/aliases, merge keys."""


def _strict_mapping(loader, node, deep=False):
    seen = set()
    for key_node, _ in node.value:
        text = getattr(key_node, "value", None)
        if text is not None:
            if text == "<<":
                raise StrictError("R8: merge key")
            if text in seen:
                raise StrictError(f"R8: duplicate key {text!r}")
            seen.add(text)
    return yaml.SafeLoader.construct_mapping(loader, node, deep)


StrictLoader.construct_mapping = _strict_mapping

FORBIDDEN_TEXT = re.compile("[\u0085\u2028\u2029]")
R12_PLAIN = [
    (re.compile(r"^[-+]?0[0-7_]+$"), "leading-zero integer (YAML 1.1 octal)"),
    (re.compile(r"^[-+]?0[bBxXoO][0-9a-fA-F_]+$"), "explicit radix literal"),
    (re.compile(r"^[-+]?[0-9][0-9]*(_[0-9_]+)+$"), "underscore digit separator"),
    (re.compile(r"^[-+]?[0-9]+(:[0-5]?[0-9])+$"), "sexagesimal number"),
    (re.compile(r"^[-+]?(yes|no|on|off|y|n)$", re.IGNORECASE),
     "YAML 1.1 boolean word"),
    (re.compile(r"^[0-9]+([eE][-+]?[0-9]+)$"), "exponent without decimal point"),
    (re.compile(r"^[0-9]+\.[0-9]*[eE][0-9]+$"), "unsigned exponent"),
    (re.compile(r"^[0-9]{4}-[0-9]{2}-[0-9]{2}$"), "plain date (must be quoted)"),
]


def parse_metadata(data):
    """Strict header parse: R6 text checks, then R8/R12-guarded YAML."""
    if data.startswith(b"\xef\xbb\xbf"):
        raise StrictError("R7: file begins with a UTF-8 BOM")
    blocks = header_lines(data)
    indents = [len(t) - len(t.lstrip(b" \t")) for t in blocks
               if t.strip() and not t.lstrip().startswith(b"#")]
    root_indent = min(indents)
    texts = []
    for text in blocks:
        body = text[root_indent:] if text.startswith(b" " * root_indent) else text
        try:
            decoded = body.decode("utf-8")
        except UnicodeDecodeError as error:
            raise StrictError(f"R6: header line is not UTF-8: {error}") from error
        if FORBIDDEN_TEXT.search(decoded):
            raise StrictError("R6: header line contains U+0085, U+2028 or U+2029")
        texts.append(decoded)
    block = "\n".join(texts)
    for event in yaml.parse(block):
        if type(event).__name__ == "AliasEvent":
            raise StrictError("R8: YAML alias")
        anchor = getattr(event, "anchor", None)
        if anchor:
            raise StrictError(f"R8: YAML anchor {anchor!r}")
        tag = getattr(event, "tag", None)
        if tag is not None and tag != "!":
            raise StrictError(f"R8: explicit tag {tag!r}")
        if type(event).__name__ == "ScalarEvent" and event.style in (None, ""):
            for pattern, why in R12_PLAIN:
                if pattern.match(event.value or ""):
                    raise StrictError(f"R12: plain scalar {event.value!r} "
                                      f"({why})")
    record = yaml.load(block, Loader=StrictLoader)
    if not isinstance(record, dict):
        raise StrictError("header block is not a YAML mapping")
    check_finite(record)
    return record


def check_finite(value, path=""):
    if isinstance(value, float) and not math.isfinite(value):
        raise StrictError(f"R13: non-finite number at {path or 'root'}")
    if isinstance(value, dict):
        for key, item in value.items():
            check_finite(item, f"{path}.{key}" if path else str(key))
    elif isinstance(value, list):
        for index, item in enumerate(value):
            check_finite(item, f"{path}[{index}]")


# --------------------------------------------------- contract + selection --
SCHEMA = json.loads((ROOT / "fht.json").read_text(encoding="utf-8"))
VALIDATOR = jsonschema.Draft202012Validator(SCHEMA,
                                            format_checker=jsonschema.FormatChecker())
RAW_MAIN = generator.RAW_MAIN
RAW_TAG = re.compile(re.escape(generator.RAW_FHT) + r"v\d+\.\d+\.\d+/fht\.json$")
W3ID_TAG = re.compile(re.escape(generator.W3ID) + r"fht/v\d+\.\d+\.\d+/?$")


def schema_selection(record):
    """docs/SCHEMA-VERSIONS.md V1/V5 (as limited by V7) applied to FHT. The
    reader's schema set is the raw-main development contract; no release
    registers FHT, so a release-form FHT URL selects nothing FHT — under V5
    it is "any other value", read as FHR with the near-miss warning, and V4
    unsupported-version never applies before publication. Returns one of
    'current', 'other-fhr' (V5: a value routed to the current FHR schema),
    'near-miss-fhr' (a release-form FHT URL: also V5, plus the reader's
    near-miss warning per FAIR-bioHeaders-Tools#125)."""
    value = record.get("schema") if isinstance(record, dict) else None
    if value == RAW_MAIN:
        return "current"
    if RAW_TAG.match(value or "") or W3ID_TAG.match(value or ""):
        return "near-miss-fhr"
    return "other-fhr"


def schema_errors(record):
    return sorted(error.message for error in VALIDATOR.iter_errors(record))


def read_record(data):
    """Strict read of an FHT file's bytes: returns (record, stated, computed).

    Raises ValueError when a conforming reader must reject before the schema
    stage. stated may differ from computed (checksum-defect vectors)."""
    record = parse_metadata(data)
    stated, _, _ = locate_checksum(data)
    computed = recomputed(data)
    return record, stated, computed


def check_parent_links(data, record, links, label):
    """T3: verify each parentLink entry against the supplied bytes."""
    derived = record.get("derivedFrom") or []
    for link in links:
        expected = link["result"]
        cited = link["statedChecksum"]
        matches = [entry for entry in derived if entry.get("checksum") == cited]
        if not matches:
            fail(f"{label}: parentLink cites {cited!r}, not present in derivedFrom")
            continue
        if expected == "unchecked":
            if link.get("file") is not None:
                fail(f"{label}: unchecked link must name no file")
            continue
        parent_path = CONFORMANCE / link["file"]
        if not parent_path.exists():
            fail(f"{label}: parent file {link['file']} missing")
            continue
        try:
            parent_checksum = verify_stated(parent_path.read_bytes())
        except ValueError as error:
            fail(f"{label}: parent {link['file']} is not self-consistent: {error}")
            continue
        if expected == "checked-pass" and parent_checksum != cited:
            fail(f"{label}: expected checked-pass, parent recomputes to "
                 f"{parent_checksum!r} != cited {cited!r}")
        if expected == "checked-fail" and parent_checksum == cited:
            fail(f"{label}: expected checked-fail, but the parent actually "
                 f"matches the cited checksum")


# -------------------------------------------------------------- the lanes --
def lane_determinism():
    first = generator.produce()
    second = generator.produce()
    if first != second:
        fail("determinism: two in-process regenerations differ")
        return
    committed = {}
    for path in sorted(CONFORMANCE.rglob("*")):
        if path.is_file() and path.name != "README.md":
            committed[str(path.relative_to(CONFORMANCE))] = path.read_bytes()
    if committed != first:
        for name in sorted(set(committed) | set(first)):
            if committed.get(name) != first.get(name):
                fail(f"determinism: {name} differs from the regenerated bytes")
        return
    owned = generator.example_outputs()
    for name, data in sorted(owned.items()):
        path = EXAMPLES / name
        if not path.exists():
            fail(f"determinism: owned example {name} is missing")
        elif path.read_bytes() != data:
            fail(f"determinism: owned example {name} differs from the "
                 f"regenerated bytes")
    note(f"determinism: {len(first)} conformance files and "
         f"{len(owned)} owned example files regenerate byte-identically")


def lane_manifest(manifest):
    ids = [entry["id"] for entry in manifest["vectors"]]
    if len(ids) != len(set(ids)):
        fail("manifest: duplicate vector ids")
    if manifest.get("retired"):
        fail("manifest: retired is expected to be empty at first publication")
    rules = set(manifest["rules"])
    on_disk = {str(path.relative_to(CONFORMANCE))
               for path in CONFORMANCE.rglob("*")
               if path.is_file() and path.name != "README.md"
               and path.name != "manifest.json"}
    referenced = {entry["file"] for entry in manifest["vectors"]}
    referenced.add("parents/parent-genome.fhr.fasta")
    if on_disk - referenced:
        fail(f"manifest: files on disk with no manifest entry: "
             f"{sorted(on_disk - referenced)}")
    if referenced - on_disk:
        fail(f"manifest: manifest entries with no file on disk: "
             f"{sorted(referenced - on_disk)}")
    for entry in manifest["vectors"]:
        if entry["format"] != generator.FORMAT:
            fail(f"{entry['id']}: unexpected format {entry['format']!r}")
        cited = set(entry.get("rules", [])) | ({entry["rule"]} if "rule" in entry else set())
        unknown = cited - rules
        if unknown:
            fail(f"{entry['id']}: cites undeclared rules {sorted(unknown)}")
    valid = [e for e in manifest["vectors"] if e["expected"] == "valid"]
    invalid = [e for e in manifest["vectors"] if e["expected"] == "invalid"]
    note(f"manifest: {len(valid)} valid, {len(invalid)} invalid vectors, "
         f"{len(rules)} rules")
    return manifest["vectors"]


def read_vector(entry):
    data = (CONFORMANCE / entry["file"]).read_bytes()
    if entry.get("compressed"):
        data = decompress(data)
    return data


def lane_vectors(vectors):
    counts = {"valid": 0, "invalid": 0, "rejected-by-shape": 0,
              "rejected-by-schema": 0, "rejected-by-fhr": 0,
              "rejected-by-link": 0}
    for entry in vectors:
        label = entry["id"]
        data = read_vector(entry)
        if entry["expected"] == "valid":
            counts["valid"] += 1
            check_expected_valid(entry, data, label)
        else:
            counts["invalid"] += 1
            check_expected_invalid(entry, data, label, counts)
    return counts


def check_expected_valid(entry, data, label):
    try:
        record = parse_metadata(data)
        stated = verify_stated(data)
    except ValueError as error:
        fail(f"{label}: a valid vector must read cleanly: {error}")
        return
    if stated != entry["checksum"]:
        fail(f"{label}: recomputed {stated!r} != manifest {entry['checksum']!r}")
    selection = schema_selection(record)
    if selection != "current":
        fail(f"{label}: valid vector must select the current contract, "
             f"got {selection}")
    errors = schema_errors(record)
    if errors:
        fail(f"{label}: valid vector must pass fht.json: {errors[:3]}")
    for key, want in entry["metadata"].items():
        got = record.get(key)
        if got != want:
            fail(f"{label}: metadata pin {key}: {got!r} != {want!r}")
    if entry.get("warnings") and "R14" in entry["warnings"]:
        schemes = [link.split(":", 1)[0].lower() for link in
                   record.get("relatedLink", [])]
        if not any(scheme not in ("http", "https", "ftp", "urn", "doi", "info")
                   for scheme in schemes):
            fail(f"{label}: declares an R14 warning but every link scheme "
                 f"is accepted")
    if entry.get("parentLink"):
        check_parent_links(data, record, entry["parentLink"], label)


def check_expected_invalid(entry, data, label, counts):
    rule = entry["rule"]
    outcome = reject_reason(entry, data)
    if outcome is None:
        fail(f"{label}: expected rejection under {rule}, but this reader "
             f"accepts it")
        return
    counts[f"rejected-by-{outcome}"] = counts.get(f"rejected-by-{outcome}", 0) + 1
    # selfChecksum classification (the shared suite's anti-accident rule):
    classification = entry["selfChecksum"]
    if classification == "matches":
        try:
            stated = verify_stated(data)
        except ValueError as error:
            fail(f"{label}: declares consistent bytes but reading fails: {error}")
    elif classification == "broken":
        try:
            stated, computed = locate_checksum(data)[0], recomputed(data)
        except ValueError as error:
            fail(f"{label}: declares a broken checksum, but it is unreachable: "
                 f"{error}")
        else:
            if stated == computed:
                fail(f"{label}: declares a broken checksum but matches")
    elif classification == "unreachable":
        try:
            locate_checksum(data)
        except ValueError:
            pass
        else:
            fail(f"{label}: declares an unreachable checksum but the root "
                 f"line is comparable")
    else:
        fail(f"{label}: unknown selfChecksum class {classification!r}")
    if entry.get("parentLink"):
        try:
            record = parse_metadata(data)
        except ValueError as error:
            fail(f"{label}: T3 vectors need readable metadata: {error}")
            return
        check_parent_links(data, record, entry["parentLink"], label)


def reject_reason(entry, data):
    """Where this reader rejects an invalid vector, per its declared rule.

    Returns 'shape' (header/checksum-text rules), 'schema' (fht.json),
    'fhr' (V5: routed to the current FHR schema, where the record's bytes
    are rejected — never the draft and not V4, per the V7 note), 'link' (T3)
    — or None when the vector is accepted, which is a manifest/fixture bug
    for anything but the T3 case handled in check_expected_invalid."""
    rule = entry["rule"]
    try:
        record = parse_metadata(data)
    except StrictError:
        return "shape" if rule in {"R2", "R5", "R6", "R7", "R8", "R10", "R12",
                                   "R13"} else None
    except ValueError:
        return "shape" if rule in {"R2", "R5", "R10"} else None
    try:
        locate_checksum(data)
    except ValueError:
        return "shape" if rule in {"R2", "R4", "R5"} else None
    if rule in {"R1", "R3", "R4"}:
        try:
            stated = locate_checksum(data)[0]
        except ValueError:
            return "shape"
        return "shape" if stated != recomputed(data) else None
    if rule == "R10":
        return "shape"
    selection = schema_selection(record)
    if entry.get("result") == "invalid-as-fhr":
        # V5 routing under the V7 note: the release-form URL selects nothing
        # FHT — the record is read against the reader's current FHR schema
        # and rejected there by its own bytes (conformance/README.md pins
        # the exact fhr.json and the rejections measured from it). This
        # reader proves the routing side: the value must be the FHT near-
        # miss, and the FHT contract itself must not reject the record, so
        # only the FHR reading can.
        if selection != "near-miss-fhr":
            return None
        return "fhr" if not schema_errors(record) else None
    if rule in {"T1", "T2", "V1", "R15"}:
        return "schema" if schema_errors(record) else None
    if rule == "T3":
        links = entry.get("parentLink") or []
        for link in links:
            if link["result"] != "checked-fail":
                continue
            parent = CONFORMANCE / link["file"]
            if parent.exists() and verify_stated(parent.read_bytes()) != link["statedChecksum"]:
                return "link"
        return None
    return None


def lane_examples():
    fastas = sorted(EXAMPLES.glob("*.fht.fasta"))
    if not fastas:
        fail("examples: no FASTA examples found")
        return
    for path in fastas:
        data = path.read_bytes()
        try:
            record = parse_metadata(data)
            stated = verify_stated(data)
        except ValueError as error:
            fail(f"examples/{path.name}: {error}")
            continue
        errors = schema_errors(record)
        if errors:
            fail(f"examples/{path.name}: fails fht.json: {errors[:3]}")
        for line, _ in split_lines(data):
            if line.startswith(PREFIX):
                body = line[len(PREFIX):]
                if b">" in body or b"@" in body:
                    fail(f"examples/{path.name}: raw record marker in a header "
                         f"line (R11): {body[:60]!r}")
        stem = path.name.split(".")[0]
        for suffix, loader in ((".fht.json", json.loads),
                               (".fht.yaml", lambda text:
                                yaml.load(text, Loader=StrictLoader))):
            sibling = EXAMPLES / f"{stem}{suffix}"
            if not sibling.exists():
                continue
            if loader(sibling.read_text(encoding="utf-8")) != record:
                fail(f"examples/{sibling.name}: does not parse to the same "
                     f"record as {path.name}")
    note(f"examples: {len(fastas)} FASTA headers recomputed and validated")


def main(argv=None):
    if not CONFORMANCE.is_dir():
        print("conformance/ not found; run scripts/make_fht_fixtures.py first",
              file=sys.stderr)
        return 1
    print(f"reader: scripts/check_fht_fixtures.py (jsonschema "
          f"{importlib.metadata.version('jsonschema')}, PyYAML "
          f"{yaml.__version__}, Python {sys.version.split()[0]})")
    lane_determinism()
    manifest = json.loads((CONFORMANCE / "manifest.json").read_text("utf-8"))
    vectors = lane_manifest(manifest)
    counts = lane_vectors(vectors)
    lane_examples()
    print(f"\nchecked {counts['valid']} valid and {counts['invalid']} invalid "
          f"vectors; rejections: {counts.get('rejected-by-shape', 0)} shape, "
          f"{counts.get('rejected-by-schema', 0)} schema, "
          f"{counts.get('rejected-by-fhr', 0)} fhr-routed (V5), "
          f"{counts.get('rejected-by-link', 0)} parent-link")

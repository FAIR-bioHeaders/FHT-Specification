"""Verify the FHT #8 fixtures with an independently written rule reader.

Repository-local runner (issue #8). It requires PyYAML and jsonschema — the
versions pinned by docs/CI.md — and no toolkit: fair-bioheaders 0.9.0 has no
FHT support, so no installed-toolkit round trip is claimed here (issue #9).

Lanes:

1. Determinism. scripts/make_fht_fixtures.py is re-run in memory (twice) and
   every regenerated byte is compared with the committed conformance/ tree
   and the owned examples/ files. This is the seed-free regeneration-and-hash
   check recorded in conformance/README.md; nothing is written.
2. Byte rules. An independently written reader (this file, adapted from the
   stdlib R1-R5 reference of FAIR-bioHeaders-Specification
   scripts/tool_survey/round6/make_fixtures.py — not from the generator's
   same-file helper) splits lines per R1, locates the single root checksum
   line per R2, applies the R5 value grammar, excludes exactly that line
   (R3) and recomputes SHA-512/256 base64 (R4, canonical charset). Gzip and
   BGZF vectors are decompressed first (R1). Valid vectors must reproduce the
   manifest checksum exactly; invalid vectors must fail in the way their
   ``selfChecksum`` class declares.
3. Header text rules. R6 (UTF-8, no U+0085/U+2028/U+2029), R7 (no BOM),
   R8 (no duplicate keys, anchors, aliases, merge keys or explicit tags),
   R10 (leading block), R12 (YAML 1.1/1.2-ambiguous plain scalars) and R13
   (finite numbers) are checked by strict parsing before any comparison.
4. Contract rules. Metadata validates against the generated fht.json
   (Draft 2020-12 dialect with an explicit FormatChecker). Schema selection
   implements docs/SCHEMA-VERSIONS.md V1/V5 as limited by the V7 note (the
   #221 ruling of 2026-11-13) for the FHT reader's actual set: only the
   raw-main URL selects a contract, and while no release registers FHT every
   release-form FHT URL is "any other value" under V5 — read as FHR, never
   the draft and not unsupported-version (V4 begins when FHT enters
   schemas/versions.json). T3 parent links are verified by
   recomputing the parent file's checksum with this same reader and
   comparing as exact strings (checked-pass / checked-fail / unchecked).
5. Manifest and inventory. The manifest covers every file on disk and every
   referenced file exists; ids are unique; cited rules exist; metadata pins
   match the parsed values.
6. Examples. Every examples/*.fht.fasta has its checksum recomputed under
   this independent reader and validates against fht.json; JSON/YAML
   siblings parse to exactly the same record as the FASTA header.

Expected outcomes come from the rule text (docs/FORMAT.md,
docs/SCHEMA-VERSIONS.md, specs/005 and conformance/README.md), never from an
implementation under test: there is no FHT implementation yet. This script is
one reference reading of those rules; the generator's self-check is another.

Local usage (pinned environment; see docs/CI.md):

    python scripts/check_fht_fixtures.py
"""

